-- One immutable, K3-only, D-1 snapshot at race x boat grain.
-- Populated atomically by scripts/build_prediction_dataset_v1.py.
CREATE TABLE core.prediction_dataset_v1 (
    race_id bigint NOT NULL REFERENCES core.race,
    race_date date NOT NULL,
    venue_code smallint NOT NULL,
    race_no smallint NOT NULL,
    boat_no smallint NOT NULL CHECK (boat_no BETWEEN 1 AND 6),
    player_id integer NOT NULL,
    motor_id bigint,
    feature_cutoff_date date NOT NULL,
    national_win_rate numeric,
    national_win_rate_status text NOT NULL,
    rating_first_course_1_to_6 double precision[] NOT NULL,
    rating_exact_second_course_1_to_6 double precision[] NOT NULL,
    rating_overall double precision NOT NULL,
    rating_short_50 double precision NOT NULL,
    rating_player_status text NOT NULL,
    rating_short_50_history_count smallint NOT NULL,
    entry_course_prob_1_to_6 double precision[],
    entry_course_status text NOT NULL,
    entry_course_history_count integer NOT NULL,
    f_suspension_state text NOT NULL,
    has_unserved_f_suspension boolean,
    current_term_f_count integer,
    current_term_f_count_status text NOT NULL,
    motor_a_base3 double precision,
    motor_a_base3_status text NOT NULL,
    base_n_meetings smallint NOT NULL,
    base_n_uses integer NOT NULL,
    base_residual_sum double precision NOT NULL,
    motor_a_current double precision,
    motor_a_current_status text NOT NULL,
    current_n_uses integer NOT NULL,
    label_eligible boolean NOT NULL,
    label_p1 smallint,
    label_p2 smallint,
    PRIMARY KEY (race_id, boat_no),
    FOREIGN KEY (race_id, boat_no) REFERENCES core.race_entry,
    CHECK (feature_cutoff_date = race_date - 1),
    CHECK (cardinality(rating_first_course_1_to_6) = 6),
    CHECK (cardinality(rating_exact_second_course_1_to_6) = 6),
    CHECK (entry_course_prob_1_to_6 IS NULL OR cardinality(entry_course_prob_1_to_6) = 6),
    CHECK ((entry_course_status IN ('READY', 'EDOGAWA_MODEL_RULE')) =
           (entry_course_prob_1_to_6 IS NOT NULL)),
    CHECK ((motor_a_base3_status = 'READY') = (motor_a_base3 IS NOT NULL)),
    CHECK ((motor_a_current_status = 'READY') = (motor_a_current IS NOT NULL)),
    CHECK ((current_term_f_count_status = 'VALID') = (current_term_f_count IS NOT NULL)),
    CHECK ((f_suspension_state = 'UNRESOLVED') = (has_unserved_f_suspension IS NULL)),
    CHECK ((label_p1 IS NOT NULL AND label_p2 IS NOT NULL) = label_eligible),
    CHECK (label_p1 IS NULL OR label_p1 IN (0, 1)),
    CHECK (label_p2 IS NULL OR label_p2 IN (0, 1))
);

CREATE INDEX prediction_dataset_v1_date_idx ON core.prediction_dataset_v1(race_date);
